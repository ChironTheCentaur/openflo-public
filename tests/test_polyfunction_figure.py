"""The polyfunctionality figure piece by piece: bars, dots, legend, the +/-
grid, the pies and the layout they sit in (draw_polyfunctionality).

Rows are generated by hand with known % of parent values, so every bar
height, dot and pie slice below is a number worked out from the rows.
Generated gate names (A, B) and group names (G1, G2) only.
"""
import numpy as np
import pytest
from matplotlib.colors import to_rgba
from matplotlib.figure import Figure

from openflo.gate_combos import combination_name, sign_patterns
from openflo.ui_polyfunction import _PIE_COLORS, draw_polyfunctionality

LABELS = ['A', 'B']
# SPICE order for two gates: A+ B+, A+ B-, A- B+, A- B-.
NAMES = [combination_name(LABELS, p) for p in sign_patterns(2)]


def _rows(sample, group, pcts):
    """One row per combination (in NAMES order) with these % of parent."""
    return [{'Sample': sample, 'Group': group, 'Combination': name,
             'Positives': sum(p), 'Count': 0, 'Parent count': 0,
             '% of parent': v}
            for name, p, v in zip(NAMES, sign_patterns(2), pcts, strict=True)]


def _two_groups():
    nan = float('nan')
    return (_rows('s1', 'G1', [10.0, 20.0, 30.0, 40.0])
            + _rows('s2', 'G1', [30.0, 20.0, 10.0, 40.0])
            + _rows('s3', 'G1', [nan, nan, nan, nan])       # left out
            + _rows('s4', 'G2', [5.0, 0.0, nan, 95.0]))


def _draw(rows, show_negative=False):
    fig = Figure()
    return fig, draw_polyfunctionality(fig, rows, LABELS, show_negative)


def test_bars_are_group_means_side_by_side():
    _fig, (ax, _grid, _pies) = _draw(_two_groups())
    bars = ax.patches
    assert len(bars) == 2 * 3                 # two groups, 3 positive combos
    width = 0.8 / 2
    # G1 mean of s1 and s2 (s3 is NaN): 20, 20, 20; G2: 5, 0, NaN.
    got = [b.get_height() for b in bars]
    assert got[:3] == [20.0, 20.0, 20.0]
    assert got[3:5] == [5.0, 0.0] and np.isnan(got[5])
    assert [b.get_width() for b in bars] == pytest.approx([width * 0.95] * 6)
    centres = [b.get_x() + b.get_width() / 2 for b in bars]
    assert centres == pytest.approx([j - width / 2 for j in range(3)]
                                    + [j + width / 2 for j in range(3)])
    assert [b.get_facecolor() for b in (bars[0], bars[3])] == [
        to_rgba('C0', 0.85), to_rgba('C1', 0.85)]
    assert ax.get_ylabel() == '% of parent'
    assert not any(t.get_visible() and t.get_text()
                   for t in ax.get_xticklabels())
    assert ax.xaxis.get_tick_params()['labelbottom'] is False


def test_dots_show_each_finite_sample_and_no_empty_line():
    _fig, (ax, _grid, _pies) = _draw(_two_groups())
    dots = [(tuple(ln.get_xdata()), tuple(ln.get_ydata())) for ln in ax.lines]
    width = 0.4
    # G1: two finite samples per combination; G2: A- B+ is NaN -> no line.
    assert dots == [
        ((0 - width / 2,) * 2, (10.0, 30.0)),
        ((1 - width / 2,) * 2, (20.0, 20.0)),
        ((2 - width / 2,) * 2, (30.0, 10.0)),
        ((0 + width / 2,), (5.0,)),
        ((1 + width / 2,), (0.0,)),
    ]
    assert {ln.get_marker() for ln in ax.lines} == {'o'}
    assert {ln.get_markersize() for ln in ax.lines} == {3}
    assert {ln.get_color() for ln in ax.lines} == {'black'}
    assert {ln.get_alpha() for ln in ax.lines} == {0.6}


@pytest.mark.parametrize('groups, legend', [
    ([''], None),                     # one unnamed group: nothing to tell apart
    (['G1'], ['G1']),
    (['', 'G2'], ['All samples', 'G2']),
])
def test_legend_only_when_there_are_groups_to_name(groups, legend):
    rows = [r for i, g in enumerate(groups)
            for r in _rows(f's{i}', g, [1.0, 2.0, 3.0, 94.0])]
    _fig, (ax, _grid, _pies) = _draw(rows)
    got = ax.get_legend()
    if legend is None:
        assert got is None
    else:
        assert [t.get_text() for t in got.get_texts()] == legend
        assert got.get_frame_on() is False
        assert {t.get_fontsize() for t in got.get_texts()} == {8}


@pytest.mark.parametrize('show_negative, n', [(False, 3), (True, 4)])
def test_sign_grid_marks_each_gate_per_combination(show_negative, n):
    _fig, (ax, grid, _pies) = _draw(_two_groups(), show_negative)
    marks = [(float(ln.get_xdata()[0]), float(ln.get_ydata()[0]),
              ln.get_marker(), ln.get_markersize(), ln.get_color())
             for ln in grid.lines]
    want = []
    for k in range(2):                # gate A on the top row (y = 1)
        for j, p in enumerate(sign_patterns(2)[:n]):
            want.append((float(j), float(1 - k),
                         'o' if p[k] else '_', 6 if p[k] else 8,
                         'black' if p[k] else 'grey'))
    assert marks == want
    assert [t.get_text() for t in grid.get_yticklabels()] == ['B', 'A']
    assert {t.get_fontsize() for t in grid.get_yticklabels()} == {8}
    assert list(grid.get_yticks()) == [0, 1]
    assert grid.get_ylim() == pytest.approx((-0.6, 1.6))
    assert list(grid.get_xticks()) == []
    assert {k: s.get_visible() for k, s in grid.spines.items()} == {
        'left': True, 'right': False, 'top': False, 'bottom': False}
    assert grid.get_shared_x_axes().joined(grid, ax)
    assert len(ax.patches) == 2 * n


def test_pies_average_the_finite_samples_of_each_group():
    _fig, (_ax, _grid, pies) = _draw(_two_groups())
    assert len(pies) == 2
    # G1: s1 has 10% in 2 gates, 50% in 1; s2 30% and 30%; s3 is NaN.
    # Mean over s1, s2: 1 gate 40%, 2 gates 20% -> slices 2/3 and 1/3.
    g1 = pies[0].patches
    assert [w.theta2 - w.theta1 for w in g1] == pytest.approx([240.0, 120.0])
    assert [w.get_facecolor() for w in g1] == [
        to_rgba(c) for c in _PIE_COLORS[1:3]]
    assert [t.get_text() for t in pies[0].texts[:2]] == ['1', '2']
    assert {t.get_fontsize() for t in pies[0].texts} == {8}
    assert pies[0].get_title() == 'G1\ngates positive'
    assert pies[0].title.get_fontsize() == 8
    # G2's one sample has a NaN, so no sample is known: the note instead.
    assert not pies[1].patches
    assert [t.get_text() for t in pies[1].texts] == ['no positive events']
    (note,) = pies[1].texts
    assert note.get_position() == (0.5, 0.5)
    assert note.get_transform() == pies[1].transAxes
    assert (note.get_fontsize(), note.get_ha(), note.get_va()) == (
        8, 'center', 'center')
    assert pies[1].axison is False
    assert pies[1].get_title() == 'G2\ngates positive'


def test_a_group_with_no_positive_events_gets_the_note():
    rows = _rows('s1', 'G1', [0.0, 0.0, 0.0, 100.0])
    _fig, (_ax, _grid, pies) = _draw(rows)
    assert not pies[0].patches
    assert [t.get_text() for t in pies[0].texts] == ['no positive events']
    assert pies[0].axison is False


def test_layout_bars_grid_then_one_column_per_pie():
    fig, (ax, grid, pies) = _draw(_two_groups())
    assert fig.axes == [ax, grid, *pies]
    gs = ax.get_subplotspec().get_gridspec()
    assert (gs.nrows, gs.ncols) == (2, 2 + 3)
    assert gs.get_height_ratios() == [3, 2 * 0.35]
    spans = [(s.rowspan, s.colspan) for s in
             (a.get_subplotspec() for a in fig.axes)]
    assert spans == [(range(1), range(3)), (range(1, 2), range(3)),
                     (range(2), range(3, 4)), (range(2), range(4, 5))]


def test_no_rows_draws_one_empty_group():
    fig, (ax, _grid, pies) = _draw([])
    assert len(ax.patches) == 3 and all(np.isnan(b.get_height())
                                        for b in ax.patches)
    assert not ax.lines and ax.get_legend() is None
    assert len(pies) == 1 and pies[0].get_title() == 'All samples\ngates positive'
    assert [t.get_text() for t in pies[0].texts] == ['no positive events']
    assert len(fig.axes) == 3


def test_groups_keep_the_order_they_first_appear_in():
    rows = (_rows('s1', 'G2', [1.0, 2.0, 3.0, 94.0])
            + _rows('s2', 'G1', [5.0, 6.0, 7.0, 82.0]))
    _fig, (ax, _grid, pies) = _draw(rows)
    assert [t.get_text() for t in ax.get_legend().get_texts()] == ['G2', 'G1']
    assert [b.get_height() for b in ax.patches] == [1.0, 2.0, 3.0,
                                                    5.0, 6.0, 7.0]
    assert ax.patches[0].get_facecolor() == to_rgba('C0', 0.85)
    assert [p.get_title() for p in pies] == ['G2\ngates positive',
                                             'G1\ngates positive']


def test_the_figure_is_laid_out_tight():
    """draw_polyfunctionality ends with tight_layout, so no axes sits where
    the plain gridspec layout (no tight_layout) would put it."""
    fig, _axes = _draw(_two_groups())
    fresh = Figure()
    gs = fresh.add_gridspec(2, 2 + 3, height_ratios=[3, 2 * 0.35])
    plain = [fresh.add_subplot(gs[0, :3]), fresh.add_subplot(gs[1, :3]),
             fresh.add_subplot(gs[:, 3]), fresh.add_subplot(gs[:, 4])]
    for laid, untouched in zip(fig.axes, plain, strict=True):
        assert laid.get_position().bounds != pytest.approx(
            untouched.get_position().bounds, abs=1e-3)
