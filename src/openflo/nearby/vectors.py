_S_ID = p.Identity(b'\4' + bytes(64), 'Device', b'\x30\x06\x02\x01\x01\x02\x01\x01')


def _scenario(name: str, role: bytes, steps: list[tuple[str, p.Message]],
              fails_at: int | None) -> dict[str, Any]:
    """A message order and where Session must refuse it (None: never). The
    builder checks the Python Session agrees before writing it down."""
    sess = p.Session(role)
    failed = None
    for i, (way, m) in enumerate(steps):
        if way == 'send':
            sess.sent(m)
            continue
        try:
            sess.received(m)
        except p.ProtocolError:
            failed = i
            break
    assert failed == fails_at, (name, failed, fails_at)
    return {'name': name, 'role': role.decode(), 'fails_at': fails_at,
            'steps': [{'way': w, 'msg': _hex(p.encode_message(m))} for w, m in steps]}


def sessions() -> list[dict[str, Any]]:
    """Message orders for Session, each with the step where it must fail."""
    S, R = 'send', 'recv'
    offer = p.Offer(bytes(16), 3000, bytes(32), 'fcs', 'a.fcs')
    d1500, d500, d1 = p.Data(b'\1' * 1500), p.Data(b'\2' * 500), p.Data(b'\3')
    r_head = [(R, _S_ID), (S, _S_ID), (S, p.PairState(False)), (R, p.PairState(False)),
              (R, p.Confirm()), (S, p.Confirm())]
    r_known = [(R, _S_ID), (S, _S_ID), (S, p.PairState(True)), (R, p.PairState(True))]
    r_flow = [(R, offer), (S, p.Accept(1000)), (R, d1500), (R, d500), (R, p.Done()),
              (S, p.Result(True, 0)), (R, p.Close())]
    i_known = [(S, _S_ID), (R, _S_ID), (S, p.PairState(True)), (R, p.PairState(True))]
    i_head = [(S, _S_ID), (R, _S_ID), (S, p.PairState(False)), (R, p.PairState(True)),
              (S, p.Confirm()), (R, p.Confirm())]
    i_flow = [(S, offer), (R, p.Accept(0)), (S, d1500), (S, d1500), (S, p.Done()),
              (R, p.Result(True, 0)), (S, p.Close())]
    ri, ii = p.ROLE_R, p.ROLE_I
    return [
        _scenario('r_pairing_then_resumed_file', ri, r_head + r_flow, None),
        _scenario('r_known_then_declined', ri, r_known + [(R, offer), (S, p.Decline(p.R_USER)),
                                                          (R, p.Close())], None),
        _scenario('r_pairstate_before_identity', ri, [(R, p.PairState(False))], 0),
        _scenario('r_second_identity', ri, [(R, _S_ID), (R, _S_ID)], 1),
        _scenario('r_offer_before_pairing', ri, r_head[:4] + [(R, offer)], 4),
        _scenario('r_offer_before_own_confirm', ri, r_head[:5] + [(R, offer)], 5),
        _scenario('r_confirm_when_both_known', ri, r_known + [(R, p.Confirm())], 4),
        _scenario('r_second_pairstate', ri, r_known + [(R, p.PairState(True))], 4),
        _scenario('r_second_confirm', ri, r_head[:5] + [(R, p.Confirm())], 5),
        _scenario('r_second_offer', ri, r_known + [(R, offer), (R, offer)], 5),
        _scenario('r_data_before_accept', ri, r_known + [(R, offer), (R, d1)], 5),
        _scenario('r_data_after_decline', ri, r_known + [(R, offer), (S, p.Decline(1)), (R, d1)], 6),
        _scenario('r_data_past_size', ri, r_known + [(R, offer), (S, p.Accept(1000)), (R, d1500),
                                                     (R, d500), (R, d1)], 8),
        _scenario('r_done_early', ri, r_known + [(R, offer), (S, p.Accept(1000)), (R, d1500),
                                                 (R, p.Done())], 7),
        _scenario('r_data_after_done', ri, r_known + r_flow[:5] + [(R, d1)], 9),
        _scenario('r_close_mid_transfer', ri, r_known + [(R, offer), (S, p.Accept(0)), (R, d1500),
                                                         (R, p.Close())], 7),
        _scenario('r_anything_after_abort', ri, r_known + [(R, p.Abort(1)), (R, offer)], 5),
        _scenario('i_pairing_then_file', ii, i_head + i_flow, None),
        _scenario('i_known_then_file', ii, i_known + i_flow, None),
        _scenario('i_confirm_before_own', ii, i_head[:4] + [(R, p.Confirm())], 4),
        _scenario('i_accept_without_offer', ii, i_known + [(R, p.Accept(0))], 4),
        _scenario('i_accept_past_size', ii, i_known + [(S, offer), (R, p.Accept(3001))], 5),
        _scenario('i_second_answer', ii, i_known + [(S, offer), (R, p.Accept(0)),
                                                    (R, p.Decline(1))], 6),
        _scenario('i_result_before_done', ii, i_known + [(S, offer), (R, p.Accept(0)),
                                                         (R, p.Result(True, 0))], 6),
        _scenario('i_offer_from_receiver', ii, i_known + [(R, offer)], 4),
        _scenario('i_data_from_receiver', ii, i_known + [(S, offer), (R, p.Accept(0)), (R, d1)], 6),
        _scenario('i_close_from_receiver', ii, i_known + [(R, p.Close())], 4),
    ]


def dumps(v: dict[str, Any]) -> str:
    """The vectors as the JSON text stored in the file."""
    return json.dumps(v, indent=1, ensure_ascii=False) + '\n'


def main(argv: list[str]) -> int:
    """Check the stored file (exit 1 if stale), or rewrite it with --write."""
    text = dumps(build())
    if '--write' in argv:
        with open(PATH, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        return 0
    with open(PATH, encoding='utf-8') as fh:
        if fh.read() != text:
            print('vectors_v1.json differs from the builder', file=sys.stderr)
            return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
