APP = 'openflo'
E_I, N_I = 0x1F2E3D4C5B6A79881F2E3D4C5B6A79881F2E3D4C5B6A79881F2E3D4C5B6A7988, bytes(range(32))
E_R, N_R = 0x0A1B2C3D4E5F60718293A4B5C6D7E8F90A1B2C3D4E5F60718293A4B5C6D7E8F9, bytes(range(32, 64))
